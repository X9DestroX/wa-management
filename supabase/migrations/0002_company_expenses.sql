-- W-A Systeme de Gestion v1.7.3 — separate company expense ledger
-- Run once in Supabase SQL Editor before using the v1.7.3 application.
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  amount numeric(14,2) not null check (amount >= 0),
  category text not null default 'Autre',
  description text not null default '',
  paid_to text not null default '',
  payment_method text not null default '',
  reference text not null default '',
  notes text not null default '',
  incurred_at timestamptz not null default now(),
  recorded_by text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists expenses_incurred_at_idx on public.expenses (incurred_at desc);
create index if not exists expenses_category_idx on public.expenses (category);
alter table public.expenses enable row level security;
drop policy if exists "expenses_all_authenticated" on public.expenses;
create policy "expenses_all_authenticated" on public.expenses for all to authenticated using (true) with check (true);
grant select, insert, update, delete on public.expenses to authenticated;
