-- W-A Systeme de Gestion v1.7.6 — Catalogue produits et stock central
-- Run once in Supabase SQL Editor. Does not delete historical sales or other records.

begin;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category text not null check (length(trim(category)) > 0),
  product_name text not null check (length(trim(product_name)) > 0),
  barcode_qr text not null default '',
  selling_price numeric(14,2) not null default 0 check (selling_price >= 0),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  notes text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists products_barcode_qr_unique
  on public.products (lower(trim(barcode_qr)))
  where trim(coalesce(barcode_qr, '')) <> '';
create index if not exists products_category_name_idx on public.products (category, product_name);
create index if not exists products_active_idx on public.products (is_active, category);

alter table public.sales add column if not exists product_id bigint;
alter table public.sales add column if not exists quantity integer not null default 1;

-- Earlier versions constrained device_type to GPS/Starlink. Inventory categories may include
-- MikroTik and other product categories, so remove that old CHECK without changing old values.
do $$
declare r record;
begin
  for r in
    select c.conname
    from pg_constraint c
    join pg_class t on t.oid=c.conrelid
    join pg_namespace n on n.oid=t.relnamespace
    where n.nspname='public' and t.relname='sales' and c.contype='c'
      and pg_get_constraintdef(c.oid) ilike '%device_type%'
  loop
    execute format('alter table public.sales drop constraint %I', r.conname);
  end loop;
end $$;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname='sales_product_id_fkey'
      and conrelid='public.sales'::regclass
  ) then
    alter table public.sales add constraint sales_product_id_fkey
      foreign key (product_id) references public.products(id) on delete restrict;
  end if;
end $$;

alter table public.sales drop constraint if exists sales_quantity_check;
alter table public.sales add constraint sales_quantity_check check (quantity >= 1);

create table if not exists public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete restrict,
  movement_type text not null check (movement_type in ('stock_initial','ajustement','vente','retour_vente')),
  quantity_delta integer not null check (quantity_delta <> 0),
  reference_table text not null default '',
  reference_id text not null default '',
  actor_id uuid references auth.users(id) on delete set null,
  actor_username text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists stock_movements_product_created_idx
  on public.stock_movements (product_id, created_at desc);
create index if not exists stock_movements_created_idx
  on public.stock_movements (created_at desc);

alter table public.products enable row level security;
alter table public.stock_movements enable row level security;

drop policy if exists "products_select_authenticated" on public.products;
create policy "products_select_authenticated" on public.products
  for select to authenticated using (true);
drop policy if exists "products_insert_authenticated" on public.products;
create policy "products_insert_authenticated" on public.products
  for insert to authenticated with check (true);
drop policy if exists "products_update_authenticated" on public.products;
create policy "products_update_authenticated" on public.products
  for update to authenticated using (true) with check (true);
-- Products are archived by the application (is_active=false), never physically deleted,
-- because historical sales and stock movements must retain their product reference.
drop policy if exists "products_delete_denied" on public.products;
create policy "products_delete_denied" on public.products
  for delete to authenticated using (false);

drop policy if exists "stock_movements_read_authenticated" on public.stock_movements;
create policy "stock_movements_read_authenticated" on public.stock_movements
  for select to authenticated using (true);
revoke insert, update, delete, truncate, references, trigger on public.stock_movements from anon, authenticated;
grant select on public.products to authenticated;
grant insert, update on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;
grant select on public.stock_movements to authenticated;
grant select, insert, update, delete on public.sales to authenticated;

create or replace function public.wa_set_product_updated_at()
returns trigger language plpgsql set search_path=public as $$
begin new.updated_at=now(); return new; end $$;
revoke all on function public.wa_set_product_updated_at() from public, anon, authenticated;
drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at before update on public.products
for each row execute function public.wa_set_product_updated_at();

-- A direct manual quantity edit is recorded as an adjustment. Sale-triggered quantity changes
-- set a transaction-local context so they are recorded as sale/return movements only once.
create or replace function public.wa_log_product_stock_change()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_context text; v_actor text; v_uid uuid;
begin
  v_uid := auth.uid();
  select username into v_actor from public.profiles where id=v_uid;
  if tg_op='INSERT' then
    if new.stock_quantity > 0 then
      insert into public.stock_movements(product_id,movement_type,quantity_delta,actor_id,actor_username,notes)
      values(new.id,'stock_initial',new.stock_quantity,v_uid,coalesce(v_actor,'système'),'Stock initial à la création du produit');
    end if;
    return new;
  end if;
  v_context := current_setting('wa.inventory_context', true);
  if new.stock_quantity is distinct from old.stock_quantity and coalesce(v_context,'') not in ('sale','sale_restore') then
    insert into public.stock_movements(product_id,movement_type,quantity_delta,actor_id,actor_username,notes)
    values(new.id,'ajustement',new.stock_quantity-old.stock_quantity,v_uid,coalesce(v_actor,'système'),'Ajustement manuel du stock');
  end if;
  return new;
end $$;
revoke all on function public.wa_log_product_stock_change() from public, anon, authenticated;
drop trigger if exists products_log_stock_insert on public.products;
create trigger products_log_stock_insert after insert on public.products
for each row execute function public.wa_log_product_stock_change();
drop trigger if exists products_log_stock_update on public.products;
create trigger products_log_stock_update after update of stock_quantity on public.products
for each row execute function public.wa_log_product_stock_change();

create or replace function public.wa_apply_sale_stock()
returns trigger language plpgsql security definer set search_path=public as $$
declare
  v_stock integer;
  v_actor uuid;
  v_username text;
begin
  v_actor := auth.uid();
  select username into v_username from public.profiles where id=v_actor;

  if tg_op='INSERT' then
    if new.product_id is null then return new; end if;
    select stock_quantity into v_stock from public.products
      where id=new.product_id and is_active=true for update;
    if not found then raise exception 'Le produit sélectionné est introuvable ou archivé.'; end if;
    if v_stock < new.quantity then
      raise exception 'Stock insuffisant pour ce produit. Stock disponible : %, quantité demandée : %.',v_stock,new.quantity;
    end if;
    perform set_config('wa.inventory_context','sale',true);
    update public.products set stock_quantity=stock_quantity-new.quantity where id=new.product_id;
    insert into public.stock_movements(product_id,movement_type,quantity_delta,reference_table,reference_id,actor_id,actor_username,notes)
    values(new.product_id,'vente',-new.quantity,'sales',new.id::text,v_actor,coalesce(v_username,'utilisateur'),'Sortie de stock liée à une vente');
    return new;
  elsif tg_op='UPDATE' then
    if old.product_id is not distinct from new.product_id and old.quantity is not distinct from new.quantity then return new; end if;
    if old.product_id is not null then
      perform set_config('wa.inventory_context','sale_restore',true);
      update public.products set stock_quantity=stock_quantity+old.quantity where id=old.product_id;
      insert into public.stock_movements(product_id,movement_type,quantity_delta,reference_table,reference_id,actor_id,actor_username,notes)
      values(old.product_id,'retour_vente',old.quantity,'sales',old.id::text,v_actor,coalesce(v_username,'utilisateur'),'Restitution du stock avant modification de vente');
    end if;
    if new.product_id is not null then
      select stock_quantity into v_stock from public.products
        where id=new.product_id and is_active=true for update;
      if not found then raise exception 'Le produit sélectionné est introuvable ou archivé.'; end if;
      if v_stock < new.quantity then
        raise exception 'Stock insuffisant pour modifier cette vente. Stock disponible : %, quantité demandée : %.',v_stock,new.quantity;
      end if;
      perform set_config('wa.inventory_context','sale',true);
      update public.products set stock_quantity=stock_quantity-new.quantity where id=new.product_id;
      insert into public.stock_movements(product_id,movement_type,quantity_delta,reference_table,reference_id,actor_id,actor_username,notes)
      values(new.product_id,'vente',-new.quantity,'sales',new.id::text,v_actor,coalesce(v_username,'utilisateur'),'Sortie de stock après modification de vente');
    end if;
    return new;
  else
    if old.product_id is not null then
      perform set_config('wa.inventory_context','sale_restore',true);
      update public.products set stock_quantity=stock_quantity+old.quantity where id=old.product_id;
      insert into public.stock_movements(product_id,movement_type,quantity_delta,reference_table,reference_id,actor_id,actor_username,notes)
      values(old.product_id,'retour_vente',old.quantity,'sales',old.id::text,v_actor,coalesce(v_username,'utilisateur'),'Retour en stock après suppression de vente');
    end if;
    return old;
  end if;
end $$;
revoke all on function public.wa_apply_sale_stock() from public, anon, authenticated;
drop trigger if exists sales_inventory_insert on public.sales;
create trigger sales_inventory_insert after insert on public.sales
for each row execute function public.wa_apply_sale_stock();
drop trigger if exists sales_inventory_update on public.sales;
create trigger sales_inventory_update after update of product_id, quantity on public.sales
for each row execute function public.wa_apply_sale_stock();
drop trigger if exists sales_inventory_delete on public.sales;
create trigger sales_inventory_delete after delete on public.sales
for each row execute function public.wa_apply_sale_stock();

-- Reuse the existing audit trigger function introduced in migration 0004.
drop trigger if exists audit_products_changes on public.products;
create trigger audit_products_changes after insert or update or delete on public.products
for each row execute function public.log_business_activity();

commit;
