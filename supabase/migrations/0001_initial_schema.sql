-- W-A Systeme de Gestion: initial cloud schema
-- Safe to run on a fresh Supabase project. This does not import or delete local SQLite data.
-- Client users must authenticate with Supabase Auth; never embed a service-role key in the desktop app.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  full_name text not null default '',
  role text not null default 'RH' check (role in ('RH', 'Gestionnaire', 'Administrateur')),
  created_at timestamptz not null default now()
);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  device_type text not null check (device_type in ('GPS', 'Starlink')),
  device_name text not null default '',
  client_name text not null default '',
  mobile text not null default '',
  device_phone text not null default '',
  sim_number text not null default '',
  gps_type text not null default '',
  address text not null default '',
  setup_by text not null default '',
  amount numeric(14,2) not null default 0,
  subscription numeric(14,2) not null default 0,
  subscription_done boolean not null default false,
  expenses numeric(14,2) not null default 0,
  sold_at timestamptz not null default now(),
  notes text not null default '',
  device_price numeric(14,2) not null default 0,
  setup_price numeric(14,2) not null default 0,
  sim_cost numeric(14,2) not null default 0,
  activation_cost numeric(14,2) not null default 0,
  benefit numeric(14,2) not null default 0,
  next_month_activation numeric(14,2) not null default 0,
  subscription_months integer not null default 0 check (subscription_months >= 0),
  actual_subscription_monthly numeric(14,2) not null default 0,
  billed_subscription_monthly numeric(14,2) not null default 3000,
  total_amount numeric(14,2) not null default 0
);

create table if not exists public.deposits (
  id bigint generated by default as identity primary key,
  amount numeric(14,2) not null check (amount >= 0),
  department text not null default 'Finance',
  reference text not null default '',
  deposited_by text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.audit (
  id bigint generated by default as identity primary key,
  username text not null default '',
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists sales_sold_at_idx on public.sales (sold_at desc);
create index if not exists sales_device_type_idx on public.sales (device_type);
create index if not exists deposits_created_at_idx on public.deposits (created_at desc);
create index if not exists audit_created_at_idx on public.audit (created_at desc);

-- Read the current signed-in employee's role without allowing users to edit their own role.
create or replace function public.current_app_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid()
$$;

revoke all on function public.current_app_role() from public;
grant execute on function public.current_app_role() to authenticated;

-- Create a minimal employee profile for each Auth user. All new accounts default to RH.
-- The trusted admin-user workflow will assign elevated roles after creating an Auth user.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  chosen_username text;
begin
  chosen_username := coalesce(
    nullif(trim(new.raw_user_meta_data ->> 'username'), ''),
    nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
    'employe'
  );
  insert into public.profiles (id, username, full_name, role)
  values (
    new.id,
    chosen_username,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), ''),
    'RH'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_wa_manager on auth.users;
create trigger on_auth_user_created_wa_manager
after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

alter table public.profiles enable row level security;
alter table public.sales enable row level security;
alter table public.deposits enable row level security;
alter table public.audit enable row level security;

-- All authenticated employees can see the user directory, but not modify profiles directly.
drop policy if exists "profiles_read_authenticated" on public.profiles;
create policy "profiles_read_authenticated"
on public.profiles for select to authenticated
using (true);

-- No direct INSERT/UPDATE/DELETE policy is granted on profiles. User administration
-- must go through a trusted server-side function using the service-role credential.
-- Sales and deposits remain editable by any authenticated employee, matching the current app.
drop policy if exists "sales_all_authenticated" on public.sales;
create policy "sales_all_authenticated"
on public.sales for all to authenticated
using (true)
with check (true);

drop policy if exists "deposits_all_authenticated" on public.deposits;
create policy "deposits_all_authenticated"
on public.deposits for all to authenticated
using (true)
with check (true);

drop policy if exists "audit_admin_read" on public.audit;
create policy "audit_admin_read"
on public.audit for select to authenticated
using (public.current_app_role() = 'Administrateur');

-- Explicit grants are still constrained by RLS.
grant select on public.profiles to authenticated;
grant select, insert, update, delete on public.sales to authenticated;
grant select, insert, update, delete on public.deposits to authenticated;
grant select on public.audit to authenticated;
